let index = fs.readFileSync(indexPath, "utf8");
if (!index.includes("payslip-print")) {
  if (!index.includes('from "./payslip-print.mjs"')) {
    index = index.replace(
      'import { listPayrollJobs, loadPayrollJob, listInvoiceJobs, loadInvoiceJob } from "./store.mjs";',
      'import { listPayrollJobs, loadPayrollJob, listInvoiceJobs, loadInvoiceJob } from "./store.mjs";\nimport { getPayslipPrint } from "./payslip-print.mjs";'
    );
  }
  const marker = 'if (req.method === "GET" && path.startsWith("/v1/payroll/") && path.endsWith("/payslip"))';
  if (!index.includes('path.endsWith("/payslip-print")')) {
    const inject = `if (req.method === "GET" && path.startsWith("/v1/payroll/") && path.endsWith("/payslip-print")) {
      const jobId = decodeURIComponent(path.slice("/v1/payroll/".length, -"/payslip-print".length));
      const result = getPayslipPrint(jobId, { tenantScope });
      if (!result.ok) return reply(result.status || 404, result);
      return reply(200, result);
    }

    `;
    if (!index.includes(marker)) {
      console.error("Could not find payslip route marker in index.mjs");
      process.exit(1);
    }
    index = index.replace(marker, inject + marker);
  }
  fs.writeFileSync(indexPath, index, "utf8");
  console.log("Patched server/index.mjs");
} else {
  console.log("index.mjs already has payslip-print");
}

