/**
 * Install GET /v1/payroll/:jobId/payslip-print on WorkPass Lohn.
 * Builds the exact DatevSheet A4 HTML used by Lohn PDF/print export.
 *
 * Usage (from baustelle root):
 *   railway ssh -s workpass-Lohn -- "cat > /tmp/patch-lohn-payslip-print.mjs" < deploy/patch-lohn-payslip-print.mjs
 *   railway ssh -s workpass-Lohn -- "node /tmp/patch-lohn-payslip-print.mjs"
 */
import fs from "fs";
import path from "path";

const root = process.cwd();
const outPath = path.join(root, "server", "payslip-print.mjs");
const indexPath = path.join(root, "server", "index.mjs");
const sheetPath = path.join(root, "datev-sheet.js");

const sheetSrc = fs.readFileSync(sheetPath, "utf8");
const cssMatch = sheetSrc.match(/const cssText = \(\) => `([\s\S]*?)`;/);
const sheetFnMatch = sheetSrc.match(/function sheetHtml\(d\) \{[\s\S]*?\n  \}\n\n  function ensureStyles/);
const wageFnMatch = sheetSrc.match(/function wageRowsHtml\([\s\S]*?\n  \}/);
const escFnMatch = sheetSrc.match(/function esc\(s\) \{[\s\S]*?\n  \}/);

if (!cssMatch || !sheetFnMatch || !wageFnMatch || !escFnMatch) {
  console.error("Could not extract DatevSheet helpers from datev-sheet.js");
  process.exit(1);
}

const moduleSrc = `/**
 * Auto-generated by patch-lohn-payslip-print.mjs — exact DatevSheet print HTML.
 */
import { loadPayrollJob } from "./store.mjs";
import { normalizeCompanyId, assertSameTenant } from "./tenant.mjs";

${escFnMatch[0]}

${wageFnMatch[0]}

const cssText = () => \`${cssMatch[1]}\`;

${sheetFnMatch[0].replace(/function ensureStyles[\s\S]*$/, "").trim()}

function formatAmount(n) {
  const x = Number(n);
  if (!Number.isFinite(x)) return "";
  return x.toLocaleString("de-DE", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function formatQty(n) {
  if (n == null || n === "") return "";
  const x = Number(n);
  if (!Number.isFinite(x)) return String(n);
  return x.toLocaleString("de-DE", { maximumFractionDigits: 2 });
}

function periodLabel(period) {
  const p = String(period || "").trim();
  if (!/^\\d{4}-\\d{2}$/.test(p)) return p;
  const [y, m] = p.split("-");
  const names = ["", "Januar", "Februar", "März", "April", "Mai", "Juni", "Juli", "August", "September", "Oktober", "November", "Dezember"];
  return \`für \${names[Number(m)] || m} \${y}\`;
}

export function payslipToSheetData(job) {
  const p = job?.payslip || {};
  const t = p.totals || {};
  const emp = { ...(job?.employee || {}), ...(p.employee || {}) };
  const co = { ...(job?.company || {}), ...(p.company || {}) };
  const bank = p.bank || {};
  const att = p.attendance || {};
  const wageRows = (Array.isArray(p.wageItems) ? p.wageItems : []).map((w) => ({
    code: w.code || w.lohnart || "",
    label: w.label || w.name || w.bezeichnung || (String(w.code || "") === "STD" ? "Stundenlohn" : ""),
    qty: formatQty(w.quantity ?? w.menge),
    amount: formatAmount(w.amount ?? w.betrag),
    taxFlag: w.taxFlag || "L",
    svFlag: w.svFlag || "L",
  }));
  const taxTotal = Number(t.payrollTax || 0) + Number(t.churchTax || 0) + Number(t.solidarity || 0);
  const svTotal = Number(t.health || 0) + Number(t.pension || 0) + Number(t.care || 0) + Number(t.unemployment || 0);
  const gross = t.gross;
  const net = t.net;
  const empId = emp.badgeId || emp.id || "";
  const iban = bank.iban || bank.IBAN || "";
  const bankName = bank.bankName || bank.name || bank.bank || "";
  return {
    companyName: co.name || "",
    logoUrl: co.logoUrl || co.meta?.hubProfile?.logoUrl || "",
    logoDataUrl: co.logoDataUrl || co.meta?.hubProfile?.logoDataUrl || "",
    titleMonth: periodLabel(p.period || job.period),
    usa: "USA/US",
    headDate: String(p.releasedAt || job.releasedAt || "").slice(0, 10),
    headPage: "Blatt 1",
    persNr: empId,
    birth: emp.birthDate || emp.dateOfBirth || "",
    stkl: emp.taxClass || emp.steuerklasse || "",
    konf: emp.confession || "",
    stTg: String(att.days || att.workedDays || att.svDays || "30"),
    pgrs: "101",
    bgrs: "1112",
    svTg: String(att.days || att.svDays || "30"),
    svNr: emp.insuranceNo || emp.svNumber || "",
    kkName: emp.healthFund || emp.krankenkasse || "",
    kkPct: emp.healthPercent != null ? formatQty(emp.healthPercent) : "",
    workDays: formatQty(att.days || att.workedDays),
    workHours: formatQty(att.hours || att.totalHours || att.workedHours),
    sender: co.name || "",
    empMeta: empId ? \`*Pers.-Nr. \${empId}*\` : "",
    empName: emp.name || "",
    empAddr: emp.address || "",
    entry: emp.entryDate || emp.startDate || "",
    taxIdMid: String(emp.taxId || emp.steuerId || "").slice(0, 4),
    hints: p.note || "",
    wageRows,
    grossTotal: formatAmount(gross),
    taxTotal: formatAmount(taxTotal),
    svTotal: formatAmount(svTotal),
    netTotal: formatAmount(net),
    netVerdienst: formatAmount(net),
    payout: formatAmount(net),
    stBrutto: formatAmount(t.taxGross ?? gross),
    lst: formatAmount(t.payrollTax),
    kist: formatAmount(t.churchTax),
    vbSoli: formatAmount(t.solidarity),
    kvB: formatAmount(t.svGross ?? gross),
    kvBeitrag: formatAmount(t.health),
    rvBeitrag: formatAmount(t.pension),
    avBeitrag: formatAmount(t.unemployment),
    pvBeitrag: formatAmount(t.care),
    bank: bankName ? \`Bank \${bankName}\` : "Bank",
    konto: iban ? \`Konto \${iban}\` : "Konto",
    agSv: formatAmount(t.employerShare),
    agExtra: formatAmount(t.umlagenTotal),
    agTotal: formatAmount(Number(t.employerShare || 0) + Number(gross || 0) + Number(t.umlagenTotal || 0)),
    payHint: "Überweisung auf das angegebene Konto",
  };
}

export function buildPayslipPrintHtml(job) {
  const data = payslipToSheetData(job);
  const body = sheetHtml(data);
  return \`<!DOCTYPE html>
<html lang="de"><head>
<meta charset="UTF-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>Entgeltabrechnung \${esc(job.period || "")}</title>
<style>\${cssText()}</style>
</head>
<body style="margin:0;background:#e8edf2;display:flex;justify-content:center;padding:12px;">
\${body}
</body></html>\`;
}

export function getPayslipPrint(jobId, { tenantScope } = {}) {
  const job = loadPayrollJob(jobId);
  if (!job) return { ok: false, status: 404, error: "Job nicht gefunden" };
  if (job.demo) return { ok: false, status: 404, error: "Demo-Job" };
  const scopeCheck = assertSameTenant(tenantScope, job.company?.id, "Payslip");
  if (!scopeCheck.ok) return { ok: false, status: 403, error: scopeCheck.error };
  return {
    ok: true,
    status: 200,
    jobId: job.jobId,
    companyId: job.company?.id || "",
    period: job.period,
    html: buildPayslipPrintHtml(job),
  };
}
`;

fs.writeFileSync(outPath, moduleSrc, "utf8");
