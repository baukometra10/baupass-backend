window.getDocsPageLang = function getDocsPageLang() {
  const langs = ["de", "en", "ar", "tr", "fr", "es", "it", "pl"];
  const code =
    localStorage.getItem("baupass-admin-v2-lang") ||
    localStorage.getItem("baupass-ui-lang") ||
    localStorage.getItem("workpass-admin-lang") ||
    "de";
  const short = String(code || "de").slice(0, 2).toLowerCase();
  return langs.includes(short) ? short : "de";
};

window.docsPageT = function docsPageT(key, vars = {}) {
  const lang = window.getDocsPageLang();
  let text =
    window.DocsPageI18n[lang]?.[key] ||
    window.DocsPageI18n.en?.[key] ||
    window.DocsPageI18n.de?.[key] ||
    key;
  for (const [k, v] of Object.entries(vars || {})) {
    text = String(text).replaceAll(`{${k}}`, String(v ?? ""));
  }
  return text;
};

window.applyDocsPageI18n = function applyDocsPageI18n() {
  const lang = window.getDocsPageLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = `SUPPIX — ${window.docsPageT("pageTitle")}`;
  document.querySelectorAll("[data-di18n]").forEach((el) => {
    const key = el.getAttribute("data-di18n");
    if (!key) return;
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      const attr = el.getAttribute("data-di18n-attr") || "placeholder";
      el.setAttribute(attr, window.docsPageT(key));
    } else if (el.tagName === "OPTION") {
      el.textContent = window.docsPageT(key);
    } else {
      const attr = el.getAttribute("data-di18n-attr");
      if (attr) el.setAttribute(attr, window.docsPageT(key));
      else el.textContent = window.docsPageT(key);
    }
  });
  const langSel = document.getElementById("docsLangSelect");
  if (langSel) {
    langSel.value = lang;
    langSel.setAttribute("aria-label", window.docsPageT("uiLang"));
  }
  if (typeof window.refreshDocsPageDynamicUi === "function") {
    window.refreshDocsPageDynamicUi({ reason: "lang" });
  }
};

window.initDocsPageLangSync = function initDocsPageLangSync() {
  const langs = ["de", "en", "ar", "tr", "fr", "es", "it", "pl"];
  const qsLang = new URLSearchParams(location.search).get("lang");
  if (qsLang && langs.includes(String(qsLang).slice(0, 2))) {
    const code = String(qsLang).slice(0, 2);
    localStorage.setItem("baupass-ui-lang", code);
    localStorage.setItem("baupass-admin-v2-lang", code);
  }
  const sel = document.getElementById("docsLangSelect");
  if (sel && !sel.dataset.bound) {
    sel.dataset.bound = "1";
    sel.addEventListener("change", () => {
      const code = sel.value;
      localStorage.setItem("baupass-ui-lang", code);
      localStorage.setItem("baupass-admin-v2-lang", code);
      window.applyDocsPageI18n();
      window.dispatchEvent(new CustomEvent("baupass-admin-lang", { detail: { lang: code } }));
    });
  }
  window.addEventListener("baupass-admin-lang", () => {
    if (sel) sel.value = window.getDocsPageLang();
    window.applyDocsPageI18n();
  });
  window.applyDocsPageI18n();
};
